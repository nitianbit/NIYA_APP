import { test, expect } from '@playwright/test';
const backend = 'http://127.0.0.1:4176';
test('employee creates and edits a shared draft, then sends one declared test intimation', async ({ page, request }, info) => {
  await page.context().route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const fixture = await (await request.get(`${backend}/__test/fixture`)).json();
  const claims = await (await request.post(`${backend}/__test/claims/setup`)).json();
  await request.post(`${backend}/__test/reset-auth-limits`);
  await page.goto('/');
  await page.getByLabel('Email or mobile number', { exact: true }).fill(fixture.email);
  await page.getByRole('button', { name: 'Send verification code', exact: true }).click();
  await expect(page.getByLabel('Verification code', { exact: true })).toBeVisible();
  const mail = await (await request.get(`${backend}/__test/mail`)).json();
  const otp = mail.filter((item: { to: string }) => item.to === fixture.email).at(-1).text.match(/\b\d{6}\b/)[0];
  await page.getByLabel('Verification code', { exact: true }).fill(otp);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  let failList = true;
  let failOptions = true;
  let releaseOptions!: () => void;
  const optionsReady = new Promise<void>(resolve => { releaseOptions = resolve; });
  let creationKey: string | undefined;
  let createdId = '';
  let createAttempts = 0;
  await page.route('**/api/employee/app/claims**', async route => {
    const path = new URL(route.request().url()).pathname;
    if (route.request().method() === 'GET' && ((path.endsWith('/claims') && failList) || (path.endsWith('/options') && failOptions))) {
      if (path.endsWith('/claims')) failList = false;
      await route.fulfill({ status: 500, json: { error: 'Synthetic read failure. Please retry.' } });
    } else if (route.request().method() === 'GET' && path.endsWith('/options')) {
      await optionsReady;
      await route.fallback();
    } else if (route.request().method() === 'POST' && path.endsWith('/claims')) {
      const response = await route.fetch();
      expect(response.status()).toBe(201);
      const result = await response.json();
      if (createAttempts++ === 0) {
        creationKey = route.request().headers()['idempotency-key'];
        expect(creationKey).toBeTruthy();
        createdId = result.claim.id;
        await route.abort('failed');
      } else {
        expect(route.request().headers()['idempotency-key']).toBe(creationKey);
        expect(result.claim.id).toBe(createdId);
        await route.fulfill({ response });
      }
    } else await route.fallback();
  });
  await page.getByRole('link', { name: 'View claims' }).click();
  await expect(page.getByRole('alert')).toContainText('Synthetic read failure');
  await expect(page.getByRole('heading', { name: 'No intimations yet' })).toHaveCount(0);
  await expect(page.getByText('Records unavailable', { exact: true })).toBeVisible();
  await page.screenshot({ path: `/tmp/niya-claims-app-list-error-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByRole('button', { name: 'New intimation', exact: true }).click();
  const form = page.getByRole('form', { name: 'Intimation draft' });
  await form.getByLabel('Hospital name').fill('Preserved during option retry');
  await form.getByRole('button', { name: 'Retry cover options' }).waitFor();
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: `/tmp/niya-claims-app-options-error-${info.project.name}.png`, fullPage: true });
  failOptions = false;
  await form.getByRole('button', { name: 'Retry cover options' }).click();
  await expect(form.getByRole('status')).toHaveText('Loading eligible cover and family members…');
  await expect(form.getByLabel('Policy', { exact: true })).toBeDisabled();
  await expect(form.getByLabel('Covered family member')).toBeDisabled();
  releaseOptions();
  await expect(form.getByRole('status')).toHaveCount(0);
  await expect(form.getByLabel('Hospital name')).toHaveValue('Preserved during option retry');
  await form.getByLabel('Policy', { exact: true }).selectOption(claims.policyId);
  await form.getByLabel('Covered family member').selectOption(claims.employeeId);
  const hospital = `Synthetic Hospital ${info.project.name}`;
  await form.getByLabel('Hospital name').fill(hospital);
  await form.getByLabel('Hospital city').fill('Synthetic City');
  await form.getByLabel('Reason for admission').fill('Synthetic admission for browser verification.');
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: `/tmp/niya-claims-app-form-${info.project.name}.png`, fullPage: true });
  await form.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(form.getByRole('alert')).toContainText('Cannot reach NIYA');
  await expect(form.getByLabel('Hospital name')).toHaveValue(hospital);
  await form.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect.poll(() => createAttempts).toBe(2);
  const detail = page.getByRole('region', { name: 'Intimation details' });
  await expect(detail.getByText(`${hospital}, Synthetic City`, { exact: true })).toBeVisible();
  const submit = detail.getByRole('button', { name: 'Submit test intimation' });
  await expect(submit).toBeDisabled();
  await detail.getByRole('button', { name: 'Edit draft' }).click();
  await form.getByLabel('Hospital city').fill('Revised City');
  await form.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(detail.getByText(`${hospital}, Revised City`, { exact: true })).toBeVisible();
  await detail.getByRole('checkbox').check();
  await submit.click();
  await expect(detail.getByText('Waiting to send', { exact: true })).toBeVisible();
  await request.post(`${backend}/__test/claims/drain`);
  await detail.getByRole('button', { name: 'Refresh status' }).click();
  await expect(detail.getByText('Test received', { exact: true })).toBeVisible();
  await expect(detail.getByText('Draft updated', { exact: true })).toBeVisible();
  await expect(detail.getByText('Intimation submitted', { exact: true })).toBeVisible();
  await expect(detail.locator('dd').filter({ hasText: /^TEST-/ })).toBeVisible();
  expect(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).not.toContain(hospital);
  await expect(page.getByText(/premium/i)).toHaveCount(0);
  await expect(page.locator('input[type="file"]')).toHaveCount(0);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(overflow).toBe(false);
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: `/tmp/niya-claims-app-${info.project.name}.png`, fullPage: true });
  const login = await (await request.post(`${backend}/api/auth/login`, { data: { email: 'hr_admin@example.test', password: fixture.password } })).json();
  const result = await (await request.get(`${backend}/api/claim-cases?employeeId=${claims.employeeId}`, { headers: { Authorization: `Bearer ${login.accessToken}` } })).json();
  expect(result.cases.some((item: { hospitalName: string; state: string }) => item.hospitalName === hospital && item.state === 'accepted')).toBe(true);
});
